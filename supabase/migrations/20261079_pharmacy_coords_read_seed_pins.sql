--
-- WHO CAN READ / WRITE WHAT (plain English):
--   • Everyone using the app — signed out (anon), guests and signed-in users (authenticated)
--     — can READ every row: a pharmacy name, its region and its pin. Nothing personal.
--   • NO app role can write: INSERT/UPDATE/DELETE/TRUNCATE are revoked from anon and
--     authenticated, and no write policy exists. Only postgres / service_role (migrations,
--     CI) change it.
--
-- WHAT IT WRITES:
--   (1) SEED — 315 rows get lat/lng copied from the facilities pharmacy with coordinates
--       that the SHIPPED matcher (utils/dutyFacilityMatch.js: strict NFC/whitespace key +
--       region-gated aliases, gated on pharmacy_coords.region) pairs them with. Computed
--       offline from the probe's data by that module and pasted as literal VALUES, so there
--       is no SQL copy of the matcher to drift (the matcher's own header forbids one).
--       source = 'facilities', verified = false. Only rows with BOTH lat and lng NULL.
--   (2) MANUAL PINS — 14 on-the-ground pins from Berke: source = 'manual', verified = true.
--       Upserted by pharmacy_name_key(name); they override (1). region is NEVER updated on
