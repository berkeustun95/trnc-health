    RAISE EXCEPTION 'expected the finished Bahrain race (api 2727) once; found %', v_n;
  END IF;
  SELECT count(*) INTO v_n FROM public.f1_results r JOIN public.f1_races f ON f.id = r.race_id
   WHERE f.api_race_id = 2727;
  IF v_n IS DISTINCT FROM 22 THEN
    RAISE EXCEPTION 'expected 22 stored results for api 2727 before the re-fetch; found %', v_n;
  END IF;
END $$;

UPDATE public.f1_races SET results_final = false WHERE api_race_id = 2727 AND session_type = 'race';

