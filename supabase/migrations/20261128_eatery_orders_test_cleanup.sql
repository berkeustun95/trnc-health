DECLARE
  c_id  constant uuid := 'bb9dad05-6bb0-4c1c-90fb-cb0a4ad68434';
  c_max constant int  := 50;
  v_slug text;
  v_cut  timestamptz := now();
  v_before int; v_del int; v_after int; v_late int;
  v_oth_n_b int; v_oth_n_a int; v_oth_m_b text; v_oth_m_a text;
BEGIN
  SELECT slug INTO v_slug FROM public.eatery_partners WHERE id = c_id;
  IF v_slug IS DISTINCT FROM 'crunchy-express' THEN
    RAISE EXCEPTION 'crunchy-express row % not found (slug %). Nothing applied.', c_id, v_slug;
  END IF;

  SELECT count(*) INTO v_before FROM public.eatery_orders WHERE partner_id = c_id AND created_at < v_cut;
  IF v_before > c_max THEN
    RAISE EXCEPTION '% Crunchy orders would be deleted (limit %): these may be real orders. Nothing applied.', v_before, c_max;
  END IF;
  SELECT count(*), md5(COALESCE(string_agg(id::text, ',' ORDER BY id), ''))
    INTO v_oth_n_b, v_oth_m_b FROM public.eatery_orders WHERE partner_id IS DISTINCT FROM c_id;

  DELETE FROM public.eatery_orders WHERE partner_id = c_id AND created_at < v_cut;
  GET DIAGNOSTICS v_del = ROW_COUNT;
  IF v_del IS DISTINCT FROM v_before THEN
    RAISE EXCEPTION 'deleted % rows, counted % beforehand', v_del, v_before;
  END IF;

  SELECT count(*) INTO v_after FROM public.eatery_orders WHERE partner_id = c_id AND created_at < v_cut;
  IF v_after IS DISTINCT FROM 0 THEN
    RAISE EXCEPTION '% Crunchy rows older than the cutoff remain', v_after;
  END IF;
  SELECT count(*), md5(COALESCE(string_agg(id::text, ',' ORDER BY id), ''))
    INTO v_oth_n_a, v_oth_m_a FROM public.eatery_orders WHERE partner_id IS DISTINCT FROM c_id;
  IF v_oth_n_a IS DISTINCT FROM v_oth_n_b OR v_oth_m_a IS DISTINCT FROM v_oth_m_b THEN
    RAISE EXCEPTION 'non-Crunchy orders changed: % -> % rows', v_oth_n_b, v_oth_n_a;
  END IF;
  SELECT count(*) INTO v_late FROM public.eatery_orders WHERE partner_id = c_id;

  RAISE NOTICE 'eatery_orders: Crunchy % before, % deleted, % remain (created after the cutoff); non-Crunchy rows unchanged at %',
    v_before, v_del, v_late, v_oth_n_a;
END $$;
