-- THE SYMPTOM. net._http_response showed a timed-out request at 05:00:00Z on 11 Oct
-- ("Timeout of 5000 ms reached"), beside duty-push's 200. It was sync-novest-morning: the
-- run itself COMPLETED — every one of the 92 active listings was stamped last_seen_at at
-- 05:00:12Z, and the function writes that stamp last, only after all writes succeed
-- (supabase/probe_novest_sync_runs.sql, read 2026-10-11 08:56Z). pg_net only stopped waiting.
-- So every run logs as a timeout and a real failure (500 + error body) is indistinguishable.
--
-- THE FIX. Same two jobs, same schedules, same Vault key ('novest_sync_key'); the only
-- change is timeout_milliseconds := 60000 (about 5x the observed 12 s). The edge function's
-- own wall-clock limit is unchanged; this is only how long pg_net waits to record the reply.
-- The commands were created by hand from supabase/functions/sync-novest/rotate-cron-to-vault.sql;
-- from here on this file owns them.
--
-- Apply: gh workflow run supabase-migrate -f file=20261106_sync_novest_cron_timeout.sql
-- ═══════════════════════════════════════════════════════════════════════════

SET ROLE postgres;

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
DECLARE j text;
BEGIN
  IF (SELECT count(*) FROM vault.secrets WHERE name = 'novest_sync_key') IS DISTINCT FROM 1 THEN
    RAISE EXCEPTION 'Vault secret novest_sync_key is missing. Nothing applied.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                  WHERE n.nspname = 'net' AND p.proname = 'http_post'
                    AND 'timeout_milliseconds' = ANY (p.proargnames)) THEN
    RAISE EXCEPTION 'net.http_post has no timeout_milliseconds parameter on this pg_net. Nothing applied.';
  END IF;
  FOREACH j IN ARRAY ARRAY['sync-novest-morning','sync-novest-evening'] LOOP
    IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = j AND active) THEN
      RAISE EXCEPTION '% is not an active job today — read before replacing. Nothing applied.', j;
    END IF;
    PERFORM cron.unschedule(j);
  END LOOP;
END $$;

SELECT cron.schedule('sync-novest-morning', '0 5 * * *', $job$
  SELECT net.http_post(
    url     := 'https://jeihxnwqytnxtytgkzgf.supabase.co/functions/v1/sync-novest',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' ||
                 (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'novest_sync_key')),
    body    := '{}'::jsonb,
    timeout_milliseconds := 60000);
$job$);

SELECT cron.schedule('sync-novest-evening', '0 15 * * *', $job$
  SELECT net.http_post(
    url     := 'https://jeihxnwqytnxtytgkzgf.supabase.co/functions/v1/sync-novest',
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' ||
                 (SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = 'novest_sync_key')),
    body    := '{}'::jsonb,
    timeout_milliseconds := 60000);
$job$);

DO $$
DECLARE v_jobs text;
BEGIN
  SELECT string_agg(jobname || ' ' || schedule, ', ' ORDER BY jobname) INTO v_jobs
    FROM cron.job WHERE jobname LIKE 'sync-novest%' OR command ILIKE '%functions/v1/sync-novest%';
  IF v_jobs IS DISTINCT FROM 'sync-novest-evening 0 15 * * *, sync-novest-morning 0 5 * * *' THEN
    RAISE EXCEPTION 'sync-novest jobs after the swap: %', coalesce(v_jobs, 'NONE');
  END IF;
  IF (SELECT count(*) FROM cron.job WHERE jobname IN ('sync-novest-morning','sync-novest-evening') AND active
        AND command LIKE '%timeout_milliseconds := 60000%' AND command LIKE '%vault.decrypted_secrets%'
        AND command NOT LIKE '%eyJ%') IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'a sync-novest job is inactive, not Vault-keyed, or missing the 60 s timeout';
  END IF;
END $$;

