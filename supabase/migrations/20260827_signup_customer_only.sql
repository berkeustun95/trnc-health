CREATE OR REPLACE FUNCTION public.handle_new_user()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  -- 2026-08-27: signup is customer-only.
  -- Every new account is created as 'customer'. Client-supplied signup
  -- metadata is ignored entirely rather than allow-listed, so passing a
  -- role straight to the auth API cannot escalate.
  -- All privileged roles are granted by an admin after signup.
  -- Existing non-customer accounts are untouched by this change.
  INSERT INTO public.profiles (id, role)
  VALUES (new.id, 'customer');

  RETURN new;
END;
$function$;

