-- runs, and so migration_ledger_check can attest that the two match.
--
-- ─── WHY IGNORE THE METADATA RATHER THAN ALLOW-LIST IT ──────────────────────
--
-- 20260719 replaced a straight copy of raw_user_meta_data->>'role' with an allow-list of
-- ('customer','provider','organizer'). That was the right fix while three roles were
-- selectable. Now that only one is, an allow-list is the wrong shape: it still READS
-- client-supplied metadata and still has to be correct about what it permits. Ignoring
-- the field entirely removes the decision instead of narrowing it — there is no longer
-- any input for a crafted `supabase.auth.signUp({ options: { data: { role: … } } })` to
-- reach. The client is not a boundary and this stops pretending it might be.
--
-- ─── WHAT IS DELIBERATELY *NOT* CHANGED ─────────────────────────────────────
--
-- profiles_role_check STILL ALLOWS ALL SIX VALUES. Narrowing it would break the admin
-- promotion path (AdminScreen.js:1692/1695/2586/2763) and orphan live accounts. As of
-- today: 176 customer, 8 provider, 2 admin, 2 organizer. The 10 non-customer accounts
-- keep every screen and every RLS grant they have now — App.js's six role branches
-- (:976-1063) are untouched, as are the provider-role policies in capture_5 and
-- get_customer_contacts().
--
-- This migration narrows who can BECOME a role at signup. It does not narrow what a role
-- IS, and it takes nothing away from anyone who already holds one.
--
-- Apply: already done. Then `node scripts/migration-ledger.mjs` and run the stamp INSERT
