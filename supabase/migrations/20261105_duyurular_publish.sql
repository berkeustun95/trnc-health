--
-- Flips every current announcement to is_published = true and every source to publish = true,
-- so the fetcher (which copies announcement_sources.publish into is_published at insert)
-- publishes new rows automatically from now on.
--
-- WHAT THIS MAKES VISIBLE, AND TO WHOM: anon and authenticated (guests included) can now read
-- announcements rows that are unexpired (RLS announcements_select_published, 20261102). Nothing
-- in the production app reads that table yet: MODULE_FLAGS.duyurular is false, there is no
-- Home entry for normal users, and search_content has no announcements arm. ADA Preview reads it.
--
-- New rows keep landing published only while their source has publish = true; a source added to
-- scripts/duyurular/sources.mjs later starts at the DEFAULT false and needs its own UPDATE.
--
-- Undo (the off switch, data only):
--   UPDATE public.announcement_sources SET publish = false;
--   UPDATE public.announcements SET is_published = false;
--
-- Apply: gh workflow run supabase-migrate -f file=20261105_duyurular_publish.sql (dry), then
-- -f apply=true. No schema change: no verify_schema object, no NOTIFY pgrst.
-- ═══════════════════════════════════════════════════════════════════════════

SET ROLE postgres;

BEGIN;

SET LOCAL lock_timeout = '5s';

UPDATE public.announcement_sources SET publish = true, updated_at = now() WHERE publish IS DISTINCT FROM true;
UPDATE public.announcements        SET is_published = true, updated_at = now() WHERE is_published IS DISTINCT FROM true;

DO $$
DECLARE
  v_src_off  int;
  v_ann_off  int;
  v_total    int;
  v_anon     int;
  v_live     int;
BEGIN
  SELECT count(*) FILTER (WHERE NOT publish) INTO v_src_off FROM public.announcement_sources;
  SELECT count(*) FILTER (WHERE NOT is_published), count(*), count(*) FILTER (WHERE expires_at > now())
    INTO v_ann_off, v_total, v_live FROM public.announcements;
  IF v_src_off IS DISTINCT FROM 0 OR v_ann_off IS DISTINCT FROM 0 THEN
    RAISE EXCEPTION 'still unpublished: % sources, % announcements', v_src_off, v_ann_off;
  END IF;
  IF v_total < 200 THEN
    RAISE EXCEPTION 'only % announcements exist (expected the ~228 the fetcher wrote): wrong database?', v_total;
  END IF;
  -- The claim is about what a client sees, so ask as anon: every unexpired row, nothing else.
  SET LOCAL ROLE anon;
  SELECT count(*) INTO v_anon FROM public.announcements;
  RESET ROLE;
  IF v_anon IS DISTINCT FROM v_live THEN
    RAISE EXCEPTION 'anon sees % rows, % are unexpired', v_anon, v_live;
  END IF;
  RAISE NOTICE 'published: % rows, % visible to anon (unexpired)', v_total, v_anon;
END $$;

