  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema='public' AND table_name='reviews' AND column_name='deleted_at') THEN
    RAISE EXCEPTION 'apply 20260928_ugc_soft_delete.sql first';
  END IF;
  RAISE NOTICE 'appointment unique is now partial';
END $$;

