SET ROLE postgres;

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
DECLARE
  c_email_a constant text := 'e5c89d1732071519678ad760eee802f4eeb2e214aaed8e24e7aa7b956d0e0d0a';
  c_email_b constant text := 'c5f67310246afe9b8deb939625d530743650b4412bcbf3ba5e852956130a025c';
  c_uid_a   constant text := '8adc421b8c7b193caf09538bd79213a7fca7e26ba090e2920b68ac92a03a484e';
  v_na int; v_nb int; v_fa text; v_fb text; v_before int; v_after int; v_new int;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.schema_migrations_applied WHERE filename = '20261132_eatery_orders_is_test.sql')
     OR to_regclass('public.order_testers') IS NULL THEN
    RAISE EXCEPTION '20261132 (order_testers) is not applied: apply it first. Nothing applied.';
  END IF;

  SELECT count(*), min(encode(pg_catalog.sha256(pg_catalog.convert_to(u.id::text, 'UTF8')), 'hex'))
    INTO v_na, v_fa FROM auth.users u
   WHERE encode(pg_catalog.sha256(pg_catalog.convert_to(lower(u.email), 'UTF8')), 'hex') = c_email_a
     AND NOT COALESCE(u.is_anonymous, false);
  SELECT count(*), min(encode(pg_catalog.sha256(pg_catalog.convert_to(u.id::text, 'UTF8')), 'hex'))
    INTO v_nb, v_fb FROM auth.users u
   WHERE encode(pg_catalog.sha256(pg_catalog.convert_to(lower(u.email), 'UTF8')), 'hex') = c_email_b
     AND NOT COALESCE(u.is_anonymous, false);
  IF v_na IS DISTINCT FROM 1 OR v_nb IS DISTINCT FROM 1 THEN
    RAISE EXCEPTION 'expected exactly 1 account per email hash: A % rows, B % rows. Nothing applied.', v_na, v_nb;
  END IF;
  IF v_fa IS DISTINCT FROM c_uid_a THEN
    RAISE EXCEPTION 'account A: the database-derived fingerprint does not equal the one given. Nothing applied.';
  END IF;

  SELECT count(*) INTO v_before FROM public.order_testers;
  INSERT INTO public.order_testers (uid_sha256, note)
  VALUES (v_fa, 'Berke live checks (A)'), (v_fb, 'Berke live checks (B)')
  ON CONFLICT (uid_sha256) DO NOTHING;
  GET DIAGNOSTICS v_new = ROW_COUNT;
  SELECT count(*) INTO v_after FROM public.order_testers;

  IF (SELECT count(*) FROM public.order_testers WHERE uid_sha256 IN (v_fa, v_fb)) IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'both fingerprints must be in order_testers after the insert';
  END IF;
  IF v_after IS DISTINCT FROM v_before + v_new THEN
    RAISE EXCEPTION 'order_testers changed by % rows, inserted %', v_after - v_before, v_new;
  END IF;

  RAISE NOTICE 'order_testers: % new, % total', v_new, v_after;
END $$;

