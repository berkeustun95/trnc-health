-- by #297); hand runs of scripts left others. They count as people on the admin screen.
--
-- WHAT IT DELETES: the guests matching this signature, created up to the last run before #297: no
-- email, role customer, a node/curl session and no other client, never refreshed, never used after
-- creation, no push token. The set must equal the list reviewed on 2026-11-05, compared by hash, so
-- one guest more, fewer or different aborts the file with nothing deleted.
-- WHY NO IDS HERE: the workflow prints this file to Actions logs, which are public on this repo. The
-- list is in the vault log 2026-11-05_admin-user-counts.md. Messages below carry no counts either.
-- Signed-up accounts cannot be reached: the signature and the DELETE both require is_anonymous, and
-- the file asserts the signed-up count is unchanged.
-- Cascades: their profiles and notifications rows.
-- NOT here: guests with no live session. Nothing proves those were scripts.
--
-- Apply: supabase-migrate. Irreversible.
-- ═══════════════════════════════════════════════════════════════════════════

SET ROLE postgres;

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
DECLARE
  v_ids      uuid[];
  v_hash     text;
  v_deleted  int;
  v_accounts bigint;
  v_guests   bigint;
BEGIN
  SELECT array_agg(u.id ORDER BY u.id::text COLLATE "C"),
         md5(string_agg(u.id::text, ',' ORDER BY u.id::text COLLATE "C"))
    INTO v_ids, v_hash
    FROM auth.users u
    JOIN public.profiles p ON p.id = u.id
   WHERE u.is_anonymous AND u.email IS NULL AND u.deleted_at IS NULL
     AND u.created_at <= '2026-11-05 12:23:00+00'
     AND p.role = 'customer' AND p.push_token IS NULL
     AND NOT COALESCE(GREATEST(u.updated_at, u.last_sign_in_at) > u.created_at + interval '1 minute', false)
     AND EXISTS (SELECT 1 FROM auth.sessions s WHERE s.user_id = u.id
                  AND (s.user_agent ILIKE 'node%' OR s.user_agent ILIKE 'curl%'))
     AND NOT EXISTS (SELECT 1 FROM auth.sessions s WHERE s.user_id = u.id
                      AND (s.refreshed_at IS NOT NULL OR s.user_agent IS NULL
                           OR (s.user_agent NOT ILIKE 'node%' AND s.user_agent NOT ILIKE 'curl%')));

  IF v_hash IS DISTINCT FROM 'c2b213c5f4c82018ebb1b1097e8e722e' THEN
    RAISE EXCEPTION 'the guests matching the signature are not the reviewed list. Nothing deleted.';
  END IF;

  SELECT count(*) FILTER (WHERE NOT is_anonymous), count(*) FILTER (WHERE is_anonymous)
    INTO v_accounts, v_guests FROM auth.users;

  DELETE FROM auth.users WHERE id = ANY(v_ids) AND is_anonymous;
  GET DIAGNOSTICS v_deleted = ROW_COUNT;

  IF v_deleted IS DISTINCT FROM 70 THEN
    RAISE EXCEPTION 'the delete did not remove exactly 70 users. Rolling back.';
  END IF;
  IF (SELECT count(*) FROM auth.users WHERE NOT is_anonymous) IS DISTINCT FROM v_accounts THEN
    RAISE EXCEPTION 'the signed-up count changed. Rolling back.';
  END IF;
  IF (SELECT count(*) FROM auth.users WHERE is_anonymous) IS DISTINCT FROM v_guests - 70 THEN
    RAISE EXCEPTION 'the guest count did not fall by exactly 70. Rolling back.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.profiles WHERE id = ANY(v_ids))
     OR EXISTS (SELECT 1 FROM public.notifications WHERE user_id = ANY(v_ids)) THEN
    RAISE EXCEPTION 'dependent rows survived the delete. Rolling back.';
  END IF;
END $$;

