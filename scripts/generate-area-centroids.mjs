#!/usr/bin/env node
// ─── constants/areaPoints.js from OSM place nodes (npm run areas:points) ──────
//
// areas.js carries names only. To give a hotel with no village (KITOB left 43 blank) an area,
// HotelsTab takes the area whose point is NEAREST its pin, within the hotel's own region —
// i.e. the area the pin "falls in", with each area's cell drawn around its village node.
// The points are OSM place nodes (ODbL; OsmAttribution is shown with every OSM pin).
//
//   node scripts/generate-area-centroids.mjs            # fresh snapshot (main Overpass, ≤ 72 h)
//   node scripts/generate-area-centroids.mjs --osm data/osm/places-….json
//
// Matching is by folded name within the region, never across: Boğaz exists in both Girne and
// İskele, 40 km apart, so a candidate must also resolve to the same region (resolveRegion).
// 'Merkez' is the district's own town. An area with no OSM node is PRINTED and left out — a
// hotel near it takes the next-nearest area rather than a guessed point.
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { AREAS_BY_REGION, areaSlug } from '../constants/areas.js'
import { resolveRegion } from '../utils/resolveRegion.js'
import { osmSnapshot } from './lib/osm-snapshot.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const OSM_ARG = args.includes('--osm') ? args[args.indexOf('--osm') + 1] : null

const MERKEZ = { nicosia: 'Lefkoşa', kyrenia: 'Girne', famagusta: 'Gazimağusa', morphou: 'Güzelyurt', iskele: 'İskele', lefke: 'Lefke' }
// OSM spells a few differently from areas.js; both sides are real names for the same place.
const ALIASES = { yenierenkoy: ['yenierenkoy', 'yeni erenkoy'], salamis: ['salamis', 'salamis harabeleri'], longbeach: ['long beach'] }
const flat = n => areaSlug(n).replace(/-/g, '')

const q = `[out:json][timeout:90];area(3602514541)->.t;(node["place"~"^(city|town|village|suburb|quarter|neighbourhood|hamlet|locality)$"](area.t););out body;`
const snap = await osmSnapshot(ROOT, 'places', q, OSM_ARG)
// Instrument check: a place query that returns nodes without coordinates matches nothing and
// reads as "OSM has no villages" (first run: `out tags`, 0/87).
if (!snap.elements.some(e => e.lat != null)) throw new Error(`snapshot has ${snap.elements.length} elements and none carries lat/lon — wrong 'out' mode`)
const nodes = snap.elements.filter(e => e.lat != null)
  .map(e => ({ id: `node/${e.id}`, lat: e.lat, lng: e.lon, place: e.tags.place,
    keys: [e.tags.name, e.tags['name:tr'], e.tags.alt_name, e.tags.old_name].filter(Boolean).flatMap(n => n.split(';')).map(flat) }))
const RANK = { city: 0, town: 1, village: 2, suburb: 3, quarter: 4, neighbourhood: 5, hamlet: 6, locality: 7 }

const out = {}, missing = [], lines = []
for (const [region, names] of Object.entries(AREAS_BY_REGION)) {
  out[region] = {}
  for (const name of names) {
    const want = name === 'Merkez' ? [flat(MERKEZ[region] || '')] : (ALIASES[flat(name)] || [name]).map(flat)
    const cands = nodes.filter(n => n.keys.some(k => want.includes(k)) && resolveRegion(n.lat, n.lng) === region)
      .sort((a, b) => RANK[a.place] - RANK[b.place])
    let c = cands[0], note = ''
    if (!c) {
      // areas.js files some villages under a different district than regions.js's anchors
      // resolve them to (Aydınköy, Gaziveren, Büyükkonuk). A name that is UNIQUE in the TRNC is
      // still that village; accept it and print the disagreement. An ambiguous name is not.
      const any = nodes.filter(n => n.keys.some(k => want.includes(k)))
      // Boğaz is in BOTH the Girne and İskele lists — a unique OSM node is then İskele's.
      const inLists = Object.values(AREAS_BY_REGION).filter(l => l.some(x => flat(x) === flat(name))).length
      if (any.length === 1 && inLists === 1) { c = any[0]; note = `  ⚠ resolves to ${resolveRegion(c.lat, c.lng)}, areas.js says ${region}` }
    }
    if (!c) { missing.push(`${region}/${name}`); continue }
    out[region][areaSlug(name)] = [+c.lat.toFixed(5), +c.lng.toFixed(5)]
    lines.push(`  ${region}/${name} → ${c.id} (${c.place})${cands.length > 1 ? `  [${cands.length} candidates, took the highest rank]` : ''}${note}`)
  }
}
const found = Object.values(out).reduce((a, r) => a + Object.keys(r).length, 0)
const total = Object.values(AREAS_BY_REGION).flat().length
console.log(lines.join('\n'))
console.log(`\nareas with an OSM point: ${found}/${total}`)
if (missing.length) console.log(`no OSM place node (left out): ${missing.join(', ')}`)

const body = Object.entries(out).map(([r, m]) => `  ${r}: {\n${Object.entries(m).map(([k, v]) => `    '${k}': [${v[0]}, ${v[1]}],`).join('\n')}\n  },`).join('\n')
writeFileSync(resolve(ROOT, 'constants/areaPoints.js'),
`// GENERATED by scripts/generate-area-centroids.mjs — do not hand-edit; re-run it.
// One point per areas.js area: the OSM place node of that village/quarter (© OpenStreetMap
// contributors, ODbL). Used to give a hotel with no village the area nearest its pin.
// OSM base: ${snap.osm3s?.timestamp_osm_base} · ${found}/${total} areas (missing: ${missing.join(', ') || 'none'})
export const AREA_POINTS = {
${body}
}
`)
console.log('→ constants/areaPoints.js')
