#!/usr/bin/env node
// ─── KTEB year roster CSV → one manual-apply migration ──────────────────────
//
//   node scripts/gen-duty-roster-sql.mjs data/kteb_duty_roster_2026-27.csv supabase/migrations/20261053_duty_roster_2026_27.sql
//
// The CSV carries date, region CODE and name only. Hours come from REGION (the pattern
// every KTEB month so far has used); address and phone are joined at apply time — see the
// header this writes.
//
// Parsing is deliberately strict: exactly 4 comma-separated fields per line and no quotes.
// KTEB names contain no commas today; the day one does, this must fail rather than shift
// a column and load a region code as a pharmacy name.

import { readFileSync, writeFileSync } from 'node:fs'

const [, , csvPath, outPath] = process.argv
if (!csvPath || !outPath) { console.error('usage: gen-duty-roster-sql.mjs <csv> <out.sql>'); process.exit(1) }

// code → [duty_list.region, open_from, open_until]. KARPAZ_1/_2 are two slots in ONE region.
export const REGION_MAP = {
  LEFKOSA:     ['Lefkoşa',     '08:00', '00:00'],
  MAGUSA:      ['Gazimağusa',  '08:00', '00:00'],
  GIRNE:       ['Girne',       '08:00', '00:00'],
  GUZELYURT:   ['Güzelyurt',   '08:00', '00:00'],
  LEFKE:       ['Lefke',       '08:00', '22:00'],
  ISKELE:      ['İskele',      '08:00', '22:00'],
  UST_MESARYA: ['Üst Mesarya', '08:00', '19:00'],
  ALT_MESARYA: ['Alt Mesarya', '08:00', '19:00'],
  KARPAZ_1:    ['Karpaz',      '08:00', '20:00'],
  KARPAZ_2:    ['Karpaz',      '08:00', '20:00'],
}

const lines = readFileSync(csvPath, 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter(l => l !== '')
if (lines[0] !== 'duty_date,region,pharmacy_name,source_page') throw new Error(`unexpected header: ${lines[0]}`)

const rows = []
const skipped = []
for (const [i, line] of lines.slice(1).entries()) {
  if (line.includes('"')) throw new Error(`line ${i + 2}: quoted field — parser is not built for it`)
  const f = line.split(',')
  if (f.length !== 4) throw new Error(`line ${i + 2}: ${f.length} fields`)
  const [date, code, rawName] = f
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) throw new Error(`line ${i + 2}: bad date ${date}`)
  if (!REGION_MAP[code]) throw new Error(`line ${i + 2}: unknown region code ${code}`)
  const name = rawName.normalize('NFC').replace(/\s+/g, ' ').trim()
  if (!name) { skipped.push(`${date} ${code}`); continue }
  rows.push({ date, code, name })
}

const dates = rows.map(r => r.date).sort()
const FROM = dates[0], TO = dates.at(-1)
const q = s => `'${s.replace(/'/g, "''")}'`

// Mesarya name → sub-region, derived from the CSV itself. Used to relabel pre-range rows.
const mesarya = new Map()
for (const r of rows) {
  if (!r.code.endsWith('_MESARYA')) continue
  const reg = REGION_MAP[r.code][0]
  if (mesarya.has(r.name) && mesarya.get(r.name) !== reg) throw new Error(`${r.name} is in both Mesarya regions`)
  mesarya.set(r.name, reg)
}

const values = rows.map(r => `(${q(r.date)}::date,${q(r.code)},${q(r.name)})`).join(',\n')
const regmap = Object.entries(REGION_MAP).map(([c, [reg, a, b]]) => `(${q(c)},${q(reg)},${q(a)},${q(b)})`).join(',\n    ')
const mesMap = [...mesarya].sort().map(([n, reg]) => `(${q(n)},${q(reg)})`).join(',\n    ')

const sql = `-- ═══════════════════════════════════════════════════════════════════════════
-- ${outPath.split('/').pop().replace('.sql', '')} — KTEB duty roster ${FROM}..${TO}, and the 9-region switch
-- ═══════════════════════════════════════════════════════════════════════════
--
-- GENERATED by scripts/gen-duty-roster-sql.mjs from ${csvPath}. Regenerate, do not hand-edit.
--
-- ${rows.length} rows over ${new Set(dates).size} dates. Skipped (empty name — KTEB has not supplied it): ${skipped.join('; ') || 'none'}.
--
-- ─── REGIONS: KTEB's nine ───────────────────────────────────────────────────
-- 'Mesarya' splits into 'Üst Mesarya' / 'Alt Mesarya'. KARPAZ_1 and KARPAZ_2 are two slots
-- in ONE region ('Karpaz'), so Karpaz shows two pharmacies a night. The code map is the
-- regmap CTE below. Pre-range 'Mesarya' rows are RELABELLED using the Mesarya
-- name → sub-region split this same CSV declares, so no row anywhere keeps the old value.
--
-- ─── WHAT THE CSV DOES NOT CARRY, AND WHERE IT COMES FROM ────────────────────
--   • HOURS — by region, the pattern of every KTEB month loaded so far
--     (Lefkoşa/Gazimağusa/Girne/Güzelyurt 08:00–00:00, Lefke/İskele 08:00–22:00,
--      Karpaz 08:00–20:00, Mesarya 08:00–19:00).
--   • ADDRESS + PHONE — from the pharmacy's MOST RECENT pre-range duty_list row (KTEB's own
--     published text), else from the ONE facilities pharmacy with exactly that name. Both
--     columns come from the same source — never an address from one and a phone from the
--     other. A name with no match, or with two facilities, gets NULL: the card then shows
--     no call button and directions search by name, which is absent-not-wrong.
--
-- public.pharmacy_coords is NOT touched.
--
-- Apply: SQL Editor, Role = postgres, whole file ONCE, copied from disk. Re-runnable: the
-- range DELETE plus ON CONFLICT make a second paste a no-op.
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

SET LOCAL lock_timeout = '5s';

-- Relabel history first: this is what the address/phone lookup below reads from.
UPDATE public.duty_list d
   SET region = m.region
  FROM (VALUES
    ${mesMap}
  ) AS m(name, region)
 WHERE d.region = 'Mesarya' AND d.name = m.name;

DELETE FROM public.duty_list WHERE duty_date BETWEEN '${FROM}' AND '${TO}';

WITH src(duty_date, code, name) AS (VALUES
${values}
),
regmap(code, region, open_from, open_until) AS (VALUES
    ${regmap}
),
prior AS (
  SELECT DISTINCT ON (name) name, address, phone
    FROM public.duty_list
   WHERE duty_date < '${FROM}'
   ORDER BY name, duty_date DESC
),
fac AS (
  SELECT name, min(address) AS address, min(phone) AS phone
    FROM public.facilities
   WHERE type = 'pharmacy'
   GROUP BY name
  HAVING count(*) = 1
)
INSERT INTO public.duty_list (duty_date, open_from, open_until, name, address, phone, region)
SELECT s.duty_date, m.open_from, m.open_until, s.name,
       CASE WHEN p.name IS NOT NULL THEN p.address ELSE f.address END,
       CASE WHEN p.name IS NOT NULL THEN p.phone   ELSE f.phone   END,
       m.region
  FROM src s
  JOIN regmap m USING (code)
  LEFT JOIN prior p ON p.name = s.name
  LEFT JOIN fac   f ON f.name = s.name
ON CONFLICT (duty_date, name) DO UPDATE
  SET open_from = excluded.open_from, open_until = excluded.open_until,
      address = excluded.address, phone = excluded.phone, region = excluded.region;

-- ─── Assertions. Each prints what it read. ──────────────────────────────────
DO $$
DECLARE
  v_n        int;
  v_dates    int;
  v_min      date;
  v_max      date;
  v_bad      text;
BEGIN
  SELECT count(*), count(DISTINCT duty_date), min(duty_date), max(duty_date)
    INTO v_n, v_dates, v_min, v_max
    FROM public.duty_list WHERE duty_date BETWEEN '${FROM}' AND '${TO}';
  IF v_n IS DISTINCT FROM ${rows.length} OR v_dates IS DISTINCT FROM ${new Set(dates).size}
     OR v_min IS DISTINCT FROM '${FROM}'::date OR v_max IS DISTINCT FROM '${TO}'::date THEN
    RAISE EXCEPTION 'range load wrong: % rows / % dates / %..% — expected ${rows.length} / ${new Set(dates).size} / ${FROM}..${TO}', v_n, v_dates, v_min, v_max;
  END IF;

  SELECT string_agg(DISTINCT coalesce(region, '(null)'), ', ') INTO v_bad
    FROM public.duty_list
   WHERE region IS NULL OR region NOT IN ('Lefkoşa','Gazimağusa','Girne','Güzelyurt','Lefke','İskele','Üst Mesarya','Alt Mesarya','Karpaz');
  IF v_bad IS NOT NULL THEN
    RAISE EXCEPTION 'duty_list carries region value(s) outside the nine: %', v_bad;
  END IF;

  -- Every date has every always-on region, and Karpaz has exactly two. Names the first
  -- offending (date, region, count) rather than a bare count.
  SELECT string_agg(format('%s %s=%s', d, r, coalesce(n, 0)), '; ') INTO v_bad
    FROM (
      SELECT d::date AS d, r, n
        FROM generate_series('${FROM}'::date, '${TO}'::date, '1 day') d
        CROSS JOIN unnest(ARRAY['Lefkoşa','Gazimağusa','Girne','Güzelyurt','Lefke','İskele','Karpaz']) r
        LEFT JOIN LATERAL (SELECT count(*) AS n FROM public.duty_list x WHERE x.duty_date = d::date AND x.region = r) c ON true
    ) z
   WHERE coalesce(n, 0) = 0 OR (r = 'Karpaz' AND n <> 2)
   LIMIT 1;
  -- ${skipped.length ? `KNOWN GAP, KTEB-side: ${skipped.join('; ')} — excluded here and nowhere else.` : ''}
  IF v_bad IS NOT NULL AND v_bad NOT IN (${skipped.map(s => { const [d, c] = s.split(' '); return q(`${d} ${REGION_MAP[c][0]}=0`) }).join(', ') || "''"}) THEN
    RAISE EXCEPTION 'coverage hole: %', v_bad;
  END IF;
END $$;

COMMIT;

-- ─── Verification after applying (read-only, run each alone) ────────────────
--   -- 1. per region, over the new range
--   SELECT region, count(*), min(duty_date), max(duty_date) FROM public.duty_list
--    WHERE duty_date BETWEEN '${FROM}' AND '${TO}' GROUP BY 1 ORDER BY 1;
--
--   -- 2. roster names with no pharmacy_coords row (what needs coordinates added)
--   SELECT DISTINCT d.name FROM public.duty_list d
--    WHERE d.duty_date BETWEEN '${FROM}' AND '${TO}'
--      AND NOT EXISTS (SELECT 1 FROM public.pharmacy_coords c WHERE c.name = d.name)
--    ORDER BY 1;
--
--   -- 3. rows that loaded with no phone
--   SELECT DISTINCT name, region FROM public.duty_list
--    WHERE duty_date BETWEEN '${FROM}' AND '${TO}' AND phone IS NULL ORDER BY 2, 1;
`

writeFileSync(outPath, sql)
console.log(`${rows.length} rows, ${new Set(dates).size} dates, ${FROM}..${TO}; skipped: ${skipped.join('; ') || 'none'}; mesarya names: ${mesarya.size}`)
