#!/usr/bin/env node
// Generates constants/countryNames.js: country names per app language, keyed by ISO region, from Node's Intl.DisplayNames.
//   node scripts/gen-country-names.mjs
// Run by hand when COUNTRY_CODES gains a country. The app never calls Intl.DisplayNames (Hermes may lack it), it reads the
// static table. English is not generated: the picker keeps COUNTRY_CODES' own English labels (so "Turkey" stays searchable).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { COUNTRY_CODES } from '../constants/countryCodes.js'

const LOCALE = { Turkish: 'tr', Arabic: 'ar', Russian: 'ru', Greek: 'el', French: 'fr', Spanish: 'es', German: 'de', Persian: 'fa' }
// Where Intl's wording reads wrong for this list: ADA's English label is "Palestine", Intl says "Palestinian Territories".
const OVERRIDE = {
  PS: { Turkish: 'Filistin', Arabic: 'فلسطين', Russian: 'Палестина', Greek: 'Παλαιστίνη', French: 'Palestine', Spanish: 'Palestina', German: 'Palästina', Persian: 'فلسطین' },
}
const regions = [...new Set(COUNTRY_CODES.flatMap(c => [].concat(c.region)))]

const out = {}
for (const [lang, loc] of Object.entries(LOCALE)) {
  const dn = new Intl.DisplayNames([loc], { type: 'region', fallback: 'none' })
  out[lang] = {}
  for (const r of regions) {
    const name = OVERRIDE[r]?.[lang] ?? dn.of(r)
    if (!name || name === r) throw new Error(`no ${lang} name for ${r}`)
    out[lang][r] = name
  }
}

const body = Object.entries(out).map(([lang, m]) =>
  `  ${lang}: {\n${Object.entries(m).map(([r, n]) => `    ${r}: ${JSON.stringify(n)},`).join('\n')}\n  },`).join('\n')
const file = `// GENERATED by scripts/gen-country-names.mjs (Node ${process.versions.node}, ICU ${process.versions.icu}). Do not edit by hand.
// Country names per app language, keyed by ISO region. English is not here: COUNTRY_CODES keeps its own English labels.
export const COUNTRY_NAMES = {
${body}
}
`
writeFileSync(fileURLToPath(new URL('../constants/countryNames.js', import.meta.url)), file)
console.log(`wrote ${Object.keys(out).length} languages x ${regions.length} regions`)
