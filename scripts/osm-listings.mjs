#!/usr/bin/env node
// OSM free listings → 20261179 (Berke 2026-11-08: free basic listings for cafés, gyms and services,
// source OSM + owner claim; NO pharmacies; partners keep the featured look).
//
//   node scripts/osm-listings.mjs <overpass.json> <partners.json>   # writes the migration, prints a summary
//
// The Overpass dump is fetched by hand (ODbL; overpass-api.de), North only — area of relation 2514541:
//   [out:json];area(3602514541)->.a;(nwr["amenity"="cafe"](area.a);nwr["leisure"="fitness_centre"](area.a);
//   nwr["shop"~"^(hairdresser|barber|laundry|dry_cleaning|copyshop)$"](area.a););out center tags;
// partners.json = eatery_partners [{name, lat, lng}] (the active ones the anon key reads).
//
// Basic info only: name, category, region, coordinates, address, phone, website. No photos, no hours
// (OSM opening_hours is a free grammar the app does not parse), no descriptions. Every row lands
// status 'staged' (20261178: Preview-only) with source 'osm' + source_id '<type>/<id>', so the subset
// stays separable (ODbL) and re-running the file is a no-op (UNIQUE (source, source_id)).
import fs from 'node:fs'
import { resolveRegion } from '../utils/resolveRegion.js'
import { inTrncFrame } from '../constants/mapSources.js'

const [rawPath, partnersPath] = process.argv.slice(2)
if (!rawPath || !partnersPath) { console.error('usage: osm-listings.mjs <overpass.json> <partners.json>'); process.exit(1) }
const raw = JSON.parse(fs.readFileSync(rawPath, 'utf8'))
const partners = JSON.parse(fs.readFileSync(partnersPath, 'utf8'))
const OUT = 'supabase/migrations/20261179_osm_free_listings.sql'

export function categoryOf(t) {
  if (t.amenity === 'cafe') return 'cafe'
  if (t.leisure === 'fitness_centre') return 'gym'
  if (t.shop === 'barber' || (t.shop === 'hairdresser' && /^(men|male|barber)$/i.test(t.hairdresser || ''))) return 'barber'
  if (t.shop === 'hairdresser') return 'hair_salon'
  if (t.shop === 'copyshop') return 'print_shop'
  if (t.shop === 'laundry' || t.shop === 'dry_cleaning') return 'laundry'
  return null
}

const metres = (a, b) => {
  const R = 6371000, toR = x => x * Math.PI / 180
  const dLat = toR(b.lat - a.lat), dLng = toR(b.lng - a.lng)
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toR(a.lat)) * Math.cos(toR(b.lat)) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}
const norm = s => s.toLocaleLowerCase('tr').replace(/[^\p{L}\p{N}]/gu, '')
const clip = (s, n) => (s == null ? null : String(s).trim().replace(/\s+/g, ' ').slice(0, n) || null)
const q = v => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

const drop = { noName: 0, noCategory: 0, outside: 0, noRegion: 0, duplicate: 0, partner: 0 }
const rows = []
for (const e of raw.elements) {
  const t = e.tags || {}
  const name = clip(t.name, 120)
  if (!name) { drop.noName++; continue }
  const category = categoryOf(t)
  if (!category) { drop.noCategory++; continue }
  const lat = e.lat ?? e.center?.lat, lng = e.lon ?? e.center?.lon
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || !inTrncFrame(lat, lng)) { drop.outside++; continue }
  const region = resolveRegion(lat, lng)
  if (!region) { drop.noRegion++; continue }
  const here = { lat, lng }
  if (partners.some(p => metres(here, p) < 80 && (norm(p.name).includes(norm(name)) || norm(name).includes(norm(p.name))))) { drop.partner++; continue }
  if (rows.some(r => r.category === category && norm(r.name) === norm(name) && metres(here, r) < 60)) { drop.duplicate++; continue }
  const street = [t['addr:street'], t['addr:housenumber']].filter(Boolean).join(' ')
  const address = clip([street, t['addr:city']].filter(Boolean).join(', '), 200)
  const website = /^https?:\/\/\S+$/i.test(t.website || t['contact:website'] || '') ? clip(t.website || t['contact:website'], 200) : null
  rows.push({
    name, category, region, lat: +lat.toFixed(6), lng: +lng.toFixed(6), address,
    phone: clip(t.phone || t['contact:phone'], 40), website, source_id: `${e.type}/${e.id}`,
  })
}
rows.sort((a, b) => a.source_id.localeCompare(b.source_id))

const byCat = rows.reduce((m, r) => ((m[r.category] = (m[r.category] || 0) + 1), m), {})
const values = rows.map(r =>
  `  (${q(r.name)}, ${q(r.category)}, ${q(r.region)}, ${r.lat}, ${r.lng}, ${q(r.address)}, ${q(r.phone)}, ${q(r.website)}, 'osm', ${q(r.source_id)}, 'staged')`).join(',\n')

const sql = `-- ═══════════════════════════════════════════════════════════
-- 20261179 — OSM free listings, STAGED (Preview only until Berke's go)
-- ═══════════════════════════════════════════════════════════
--
-- GENERATED by scripts/osm-listings.mjs from an Overpass dump of OpenStreetMap, ${new Date().toISOString().slice(0, 10)}.
-- Data © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright). The rows stay
-- identifiable (source = 'osm', source_id = '<type>/<id>') and the map and detail page carry the OSM credit.
--
-- What: ${rows.length} free basic listings (Berke 2026-11-08) — ${Object.entries(byCat).map(([k, v]) => `${k} ${v}`).join(', ')}.
-- Basic info only: name, category, region (utils/resolveRegion.js), coordinates, address, phone, website.
-- Dropped by the generator: ${Object.entries(drop).map(([k, v]) => `${k} ${v}`).join(', ')}.
-- No pharmacies (the pharmacy rule stands); partner eateries are skipped where OSM duplicates them.
--
-- status 'staged' (20261178): readable ONLY with the ADA Preview key. Production sees none of it.
-- Publishing is a separate migration on Berke's go. Re-running this file inserts nothing new
-- (ON CONFLICT (source, source_id) DO NOTHING).
--
-- Apply: gh workflow run supabase-migrate -f file=20261179_osm_free_listings.sql (dry), then -f apply=true.

SET ROLE postgres;

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.places'::regclass
                  AND conname = 'places_status_check' AND pg_get_constraintdef(oid) LIKE '%staged%') THEN
    RAISE EXCEPTION 'REFUSING: 20261178 (staged status) is not applied';
  END IF;
END $$;

INSERT INTO public.places (name, category, region, latitude, longitude, address, phone, website, source, source_id, status)
VALUES
${values}
ON CONFLICT ON CONSTRAINT places_source_source_id_key DO NOTHING;

DO $$
DECLARE v_staged int; v_active int;
BEGIN
  SELECT count(*) FILTER (WHERE status = 'staged'), count(*) FILTER (WHERE status <> 'staged')
    INTO v_staged, v_active FROM public.places WHERE source = 'osm';
  IF v_active <> 0 THEN RAISE EXCEPTION 'an OSM row is not staged (%)', v_active; END IF;
  IF v_staged < ${rows.length} THEN RAISE EXCEPTION 'expected at least ${rows.length} staged OSM rows, found %', v_staged; END IF;
  RAISE NOTICE '20261179 OK: % staged OSM listings, none public', v_staged;
END $$;

COMMIT;
`
fs.writeFileSync(OUT, sql)
console.log(`${OUT}: ${rows.length} rows`, byCat, 'dropped', drop)
