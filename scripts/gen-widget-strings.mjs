#!/usr/bin/env node
// widgets/strings.json → the iOS widget extension's strings (targets/widgets):
//   <code>.lproj/Localizable.strings  gallery name + description, in the PHONE's language (OS-owned)
//   Strings.generated.swift           widget content, in ADA's language (App Group 'lang')
// Android reads the JSON directly (widgets/shortcuts.js, plugins/withWidgetStrings.js).
//
//   node scripts/gen-widget-strings.mjs           write
//   node scripts/gen-widget-strings.mjs --check   fail if the committed files differ
//
// ar/fa .lproj live in the EXTENSION bundle only. CLAUDE.md's RTL rule is about the APP bundle
// (expo.locales); the app's own localizations are unchanged by this.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET = join(ROOT, 'targets/widgets')
const strings = JSON.parse(readFileSync(join(ROOT, 'widgets/strings.json'), 'utf8'))
const GALLERY_KEYS = ['shortcutsName', 'shortcutsDesc']
const HEADER = '// GENERATED by scripts/gen-widget-strings.mjs from widgets/strings.json. Do not edit.\n'

const keys = Object.keys(strings.en)
for (const [code, items] of Object.entries(strings)) {
  const missing = keys.filter(k => !items[k]?.trim())
  if (missing.length) { console.error(`✗ widgets/strings.json: ${code} is missing ${missing.join(', ')}`); process.exit(1) }
}

const q = s => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
const files = {}
for (const [code, items] of Object.entries(strings)) {
  files[join(TARGET, `${code}.lproj/Localizable.strings`)] =
    `/* GENERATED by scripts/gen-widget-strings.mjs from widgets/strings.json. Do not edit. */\n`
    + GALLERY_KEYS.map(k => `${q(k)} = ${q(items[k])};`).join('\n') + '\n'
}
files[join(TARGET, 'Strings.generated.swift')] = HEADER
  + 'let widgetStrings: [String: [String: String]] = [\n'
  + Object.entries(strings).map(([code, items]) =>
    `  ${q(code)}: [\n` + keys.map(k => `    ${q(k)}: ${q(items[k])},`).join('\n') + '\n  ],').join('\n')
  + '\n]\n'

const check = process.argv.includes('--check')
const stale = []
for (const [file, text] of Object.entries(files)) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (current === text) continue
  if (check) { stale.push(file.slice(ROOT.length + 1)); continue }
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
}
if (stale.length) {
  console.error(`✗ widget strings out of date: ${stale.join(', ')}\n  run: node scripts/gen-widget-strings.mjs`)
  process.exit(1)
}
console.log(`✓ widget strings: ${Object.keys(strings).length} languages × ${keys.length} keys${check ? ' (in sync)' : ' written'}`)
