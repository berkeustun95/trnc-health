#!/usr/bin/env node
// ─── constants/dovecPreview.js — the mock fixture, as the app would read it ──
//
//   node scripts/build-dovec-preview.mjs           # regenerate
//   node scripts/build-dovec-preview.mjs --check   # fail if the committed file is stale
//
// The Döveç page previews against the SAME fixture the sync test uses, pushed through the SAME
// mapper (supabase/functions/_shared/dovec-feed.mjs), so a mapping change shows up on the device
// and not only in a test log. Then it applies what the database would: go-live (rows active), the
// photo rule (a project needs a cover, a unit needs a photo) and the mirror (each media URL becomes
// the bundled placeholder of the same file name in assets/dovec-mock/).
//
// Used only when __DEV__ && EXPO_PUBLIC_DOVEC_MOCK=1 (utils/loadDovecProjects.js). Fixture rows are
// flagged fromFixture so a tap on them is never logged (constants/dovec.js).

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { mapFeed } from '../supabase/functions/_shared/dovec-feed.mjs'
import { AREAS_BY_REGION, areaSlug } from '../constants/areas.js'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = resolve(ROOT, 'constants/dovecPreview.js')
const fixture = JSON.parse(readFileSync(resolve(ROOT, 'supabase/functions/sync-dovec/fixtures/dovec-mock.json'), 'utf8'))
const feed = fixture.pages.flatMap(p => p.data)
const { projects, units } = await mapFeed(feed, { areasByRegion: AREAS_BY_REGION, areaSlugOf: areaSlug })

const asset = url => new URL(url).pathname.split('/').pop().replace(/\.jpg$/, '')
// Deterministic fake uuids: the page keys on id; nothing is ever written with them.
const uuid = (kind, ext) => `00000000-0000-4000-d0${kind}-${ext.replace(/\D/g, '').padStart(12, '0')}`

const out = projects.filter(p => p.media.length).map(p => ({
  id: uuid('0a', p.external_id),
  external_id: p.external_id,
  name: p.name,
  description: p.description,
  project_status: p.project_status,
  construction_progress: p.construction_progress,
  delivery_date: p.delivery_date,
  unit_types: p.unit_types,
  price_from: p.price_from,
  currency: p.currency,
  price_on_request: p.price_on_request,
  district: p.district,
  area: p.area,
  address: p.address,
  latitude: p.latitude,
  longitude: p.longitude,
  location_precision: p.location_precision,
  cover: asset(p.media[0].url),
  units: units.filter(u => u.project_external_id === p.external_id && u.media.length).map(u => ({
    id: uuid('0b', u.external_id),
    title: u.title,
    property_type: u.property_type,
    price: u.price,
    price_on_request: u.price_on_request,
    currency: u.currency,
    bedrooms: u.bedrooms,
    living_rooms: u.living_rooms,
    bathrooms: u.bathrooms,
    area_sqm: u.area_sqm,
    floor: u.floor,
    photo: asset(u.media[0].url),
  })),
}))

const names = [...new Set(out.flatMap(p => [p.cover, ...p.units.map(u => u.photo)]))].sort()
const js = `// GENERATED by scripts/build-dovec-preview.mjs from supabase/functions/sync-dovec/fixtures/dovec-mock.json.
// Do not edit by hand: change the fixture or the mapper and regenerate. FICTIONAL MOCK DATA.
/* eslint-disable */
const IMG = {
${names.map(n => `  '${n}': require('../assets/dovec-mock/${n}.jpg'),`).join('\n')}
}

export const DOVEC_PREVIEW_PROJECTS = ${JSON.stringify(out, null, 2)}
  .map(p => ({ ...p, fromFixture: true, coverSource: IMG[p.cover],
    units: p.units.map(u => ({ ...u, photoSource: IMG[u.photo] })) }))
`

if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8')
  if (cur !== js) { console.error('constants/dovecPreview.js is stale — run: node scripts/build-dovec-preview.mjs'); process.exit(1) }
  console.log(`dovec preview: OK (${out.length} projects, ${out.reduce((n, p) => n + p.units.length, 0)} units, matches the fixture + mapper)`)
} else {
  writeFileSync(OUT, js)
  console.log(`wrote ${OUT} (${out.length} projects)`)
}
